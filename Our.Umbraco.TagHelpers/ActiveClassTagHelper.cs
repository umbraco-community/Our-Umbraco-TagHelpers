using Microsoft.AspNetCore.Razor.TagHelpers;
using System.Text.Encodings.Web;
using Umbraco.Cms.Core.Web;
using Umbraco.Extensions;
using Microsoft.AspNetCore.Mvc.TagHelpers;
using System;
using System.Threading.Tasks;
using Umbraco.Cms.Core;
using Umbraco.Cms.Core.Models.PublishedContent;
using Umbraco.Cms.Core.Routing;
using Umbraco.Cms.Core.Services;
using Umbraco.Cms.Core.Services.Navigation;

namespace Our.Umbraco.TagHelpers
{
    /// <summary>
    /// An attribute TagHelper that only works with <a> tags
    /// 
    /// Applying the attribute our-is-active-page="navi-active"
    /// Will apply the CSS class name navi-active to the class attribute
    /// if the value in the href of the <a> compared to the page being rendered
    /// is the current page or part of an ancestor
    /// </summary>"
    [HtmlTargetElement("*", Attributes = tagHelperAttributes)]
    [HtmlTargetElement("a", Attributes = tagHelperAttributeName)]
    public class ActiveClassTagHelper : TagHelper
    {
        private const string tagHelperAttributeName = "our-active-class";
        private const string tagHelperAttributeHrefName = "our-active-href";
        private const string tagHelperAttributes = tagHelperAttributeName + ", " + tagHelperAttributeHrefName;

        private IUmbracoContextAccessor _umbracoContextAccessor;
        private readonly IPublishedUrlProvider _publishedUrlProvider;
        private readonly IDocumentNavigationQueryService _documentNavigationQueryService;

        public ActiveClassTagHelper(IUmbracoContextAccessor umbracoContextAccessor, IPublishedUrlProvider publishedUrlProvider, IDocumentNavigationQueryService documentNavigationQueryService)
        {
            _umbracoContextAccessor = umbracoContextAccessor;
            _publishedUrlProvider = publishedUrlProvider;
            _documentNavigationQueryService = documentNavigationQueryService;
        }

        /// <summary>
        /// The CSS class name you wish to append to the class attribute
        /// on an <a> tag when the page is active/selected
        /// </summary>
        [HtmlAttributeName(tagHelperAttributeName)]
        public string? ActiveClassName { get; set; }


        /// <summary>
        /// If you wish to add an active CSS class on another DOM element than an <a>
        /// You can use this attribute to pass a link to the page to check in conjuction with `our-active-class` attribute
        /// </summary>
        [HtmlAttributeName("our-active-href")]
        public string? ActiveLink { get; set; }

        public override async Task ProcessAsync(TagHelperContext context, TagHelperOutput output)
        {
            // Remove the attribute 
            // We don't want it in the markup we send down to the page
            output.Attributes.RemoveAll(tagHelperAttributeName);

            var ctx = _umbracoContextAccessor.GetRequiredUmbracoContext();

            // Only a routed Umbraco page has a current page to compare the link with
            var publishedRequest = ctx.PublishedRequest;
            if (publishedRequest?.PublishedContent is null)
            {
                return;
            }

            // If we have active link prop set use that othewise try to find the href attribute on an <a> and its value
            var href = string.IsNullOrEmpty(ActiveLink) ? output.Attributes["href"]?.Value.ToString() : ActiveLink;
            if (string.IsNullOrEmpty(href))
            {
                return;
            }
            
            // The link is active when it points at the current page or one of its ancestors.
            // Compare the link with those pages' URLs, generated by Umbraco for the current culture, rather than
            // looking the link up as a route: a route lookup misses pages under culture domains (/en/page-a/
            // is stored relative to the domain's root node), see issue #97.
            // Resolving against the current request also turns a relative href into an absolute URL.
            if (!Uri.TryCreate(publishedRequest.Uri, href, out var link))
            {
                return;
            }

            var currentPage = publishedRequest.PublishedContent;
            if (!_documentNavigationQueryService.TryGetAncestorsOrSelfKeys(currentPage.Key, out var pageKeys))
            {
                pageKeys = new[] { currentPage.Key };
            }

            foreach (var pageKey in pageKeys)
            {
                var pageUrl = _publishedUrlProvider.GetUrl(pageKey, UrlMode.Absolute, publishedRequest.Culture, publishedRequest.Uri);
                if (Uri.TryCreate(pageUrl, UriKind.Absolute, out var pageUri) && IsSamePage(link, pageUri))
                {
                    output.AddClass(ActiveClassName, HtmlEncoder.Default);
                    return;
                }
            }
        }

        /// <summary>Same host and path, ignoring case, a trailing slash, the query string and the fragment.</summary>
        private static bool IsSamePage(Uri link, Uri page) =>
            string.Equals(link.Host, page.Host, StringComparison.OrdinalIgnoreCase)
            && string.Equals(link.AbsolutePath.TrimEnd('/'), page.AbsolutePath.TrimEnd('/'), StringComparison.OrdinalIgnoreCase);
    }
}
